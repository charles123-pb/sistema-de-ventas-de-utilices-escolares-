import { test, expect } from "@playwright/test";

test("caja registra empresa o persona sin perder carrito y permite venta rápida", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("Usuario",{exact:true}).fill("administrador");
  await page.getByLabel("Contraseña",{exact:true}).fill("prueba-segura-123");
  await page.getByRole("button",{name:"Iniciar sesión"}).click();
  await expect(page.getByRole("heading",{name:"Tu librería, de un vistazo"})).toBeVisible();
  const product=await page.request.post("/api/productos",{headers:{Origin:new URL(page.url()).origin},data:{codigo:"CAJA-CLIENTE",nombre:"[PRUEBA] Lapicero caja",categoria_id:2,costo:"1.00",precio:"2.00",stock:10,stock_minimo:1,activo:true}});
  expect(product.ok(),await product.text()).toBeTruthy();
  await page.goto("/app/caja");
  await page.getByLabel("Buscar productos").fill("CAJA-CLIENTE");
  await page.locator(".sale-product").click();
  await page.getByLabel("Cantidad de [PRUEBA] Lapicero caja").fill("2");
  await expect(page.getByRole("radio",{name:"Consumidor final",exact:true})).toBeChecked();
  await page.getByRole("radio",{name:"Empresa con RUC",exact:true}).check();
  await expect(page.getByRole("button",{name:"Confirmar venta pagada"})).toBeDisabled();
  await page.getByRole("button",{name:"Nuevo cliente",exact:true}).click();
  await page.getByLabel("Razón social",{exact:true}).fill("[PRUEBA] Librería Empresa");
  await page.getByLabel("RUC",{exact:true}).fill("20123456789");
  await page.getByLabel("Dirección de la empresa",{exact:true}).fill("Jr. Prueba 456, Huamanga");
  await page.getByRole("button",{name:"Guardar y seleccionar",exact:true}).click();
  await expect(page.locator(".checkout-customer-selected")).toContainText("[PRUEBA] Librería Empresa");
  await expect(page.getByLabel("Cantidad de [PRUEBA] Lapicero caja")).toHaveValue("2");
  await page.getByLabel("Efectivo recibido (S/)").fill("10.00");
  await page.getByRole("button",{name:"Confirmar venta pagada"}).click();
  await expect(page.locator(".document")).toContainText("Cliente: [PRUEBA] Librería Empresa");
  await expect(page.locator(".document")).toContainText("RUC: 20123456789");
  await expect(page.locator(".document")).toContainText("Jr. Prueba 456, Huamanga");
  await expect(page.locator(".document")).toContainText("NO ES UN COMPROBANTE TRIBUTARIO");
  await page.getByRole("link",{name:"Volver a caja"}).click();
  await page.getByLabel("Buscar productos").fill("CAJA-CLIENTE");
  await page.locator(".sale-product").click();
  await page.getByRole("radio",{name:"Persona",exact:true}).check();
  await page.getByRole("button",{name:"Nuevo cliente",exact:true}).click();
  await page.getByLabel("Nombre del cliente",{exact:true}).fill("[PRUEBA] Persona sin documento");
  await page.getByRole("button",{name:"Guardar y seleccionar",exact:true}).click();
  await expect(page.locator(".checkout-customer-selected")).toContainText("Persona sin documento");
  await page.getByRole("radio",{name:"Empresa con RUC",exact:true}).check();
  await page.getByLabel("Buscar cliente por nombre o documento").fill("20123456789");
  await page.getByLabel("Cliente",{exact:true}).selectOption({label:"[PRUEBA] Librería Empresa · 20123456789"});
  await expect(page.locator(".checkout-customer-selected")).toContainText("Librería Empresa");
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:"test-results/caja-cliente-empresa-movil.png",fullPage:true});
  await page.getByRole("radio",{name:"Consumidor final",exact:true}).check();
  await expect(page.locator(".cart-line")).toHaveCount(1);
  await page.getByLabel("Efectivo recibido (S/)").fill("5.00");
  await page.getByRole("button",{name:"Confirmar venta pagada"}).click();
  await expect(page.locator(".document")).toContainText("Cliente: Consumidor final");
});
